import "server-only";

import { GoogleGenAI } from "@google/genai";
import { cacheLife, cacheTag } from "next/cache";

import { toDate, type IsoDate } from "@/lib/date";
import { env } from "@/lib/env";
import type { Locale } from "@/lib/i18n/routing";
import { MENSA_CACHE_TAG } from "./cache";
import {
  guruMeals,
  guruPrompt,
  guruResponseSchema,
  guruSystemInstruction,
  parseGuruAnswer,
  type GuruAdvice,
} from "./guru-prompt";
import { getMenu } from "./queries";

/** Free tier model of the Gemini API; override with `GEMINI_MODEL` */
const DEFAULT_MODEL = "gemini-3.5-flash-lite";
const TIMEOUT_MS = 20_000;

/** The guru is only shown when a Gemini API key is configured */
export function isGuruEnabled(): boolean {
  return Boolean(env.GEMINI_API_KEY);
}

/**
 * The guru's pick for a day, generated by Gemini from all meals and their ratings.
 * Cached per day and language, so the free tier quota is only used about once a day; a new
 * rating or menu change (mensa tag) lets the guru reconsider. Errors are not cached.
 * `null` if there is no menu that day.
 */
export async function getGuruAdvice(
  date: IsoDate,
  locale: Locale,
): Promise<GuruAdvice | null> {
  "use cache";
  cacheTag(MENSA_CACHE_TAG);
  cacheLife("days");

  if (!env.GEMINI_API_KEY) return null;
  const meals = guruMeals(await getMenu(date), locale);
  if (meals.length === 0) return null;

  const weekday = new Intl.DateTimeFormat("en", {
    weekday: "long",
    day: "numeric",
    month: "long",
    timeZone: "Europe/Berlin",
  }).format(toDate(date));

  const ai = new GoogleGenAI({ apiKey: env.GEMINI_API_KEY });
  const response = await ai.models.generateContent({
    model: env.GEMINI_MODEL ?? DEFAULT_MODEL,
    contents: guruPrompt(meals, weekday),
    config: {
      systemInstruction: guruSystemInstruction(locale),
      responseMimeType: "application/json",
      responseJsonSchema: guruResponseSchema(meals),
      abortSignal: AbortSignal.timeout(TIMEOUT_MS),
    },
  });
  return parseGuruAnswer(response.text, meals);
}
